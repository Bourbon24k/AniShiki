const INDEX = new Map(ALL_GENRES.map((g) => [g.toLowerCase(), g]));

/**
 * Привести произвольную строку к каноничному названию жанра.
 * Возвращает null, если такого жанра нет — тогда это обычный поисковый запрос.
 * @param {string} value
 */
export function canonicalGenre(value) {
	const raw = String(value || '')
		.trim()
		.toLowerCase()
		.replace(/ё/g, 'е');
	if (!raw) return null;
	// Прямое совпадение (с поправкой на «ё»).
	for (const [key, name] of INDEX) {
		if (key.replace(/ё/g, 'е') === raw) return name;
	}
	return null;
}

/** Группа, в которой лежит жанр («Жанры» / «Аудитория» / «Тематика»). */
export function genreGroup(name) {
	const lower = String(name || '').toLowerCase();
	return GENRE_GROUPS.find((g) => g.items.some((i) => i.toLowerCase() === lower))?.name || null;
}
